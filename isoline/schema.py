"""Feature schema (Phase 2).

The ORDER of FEATURE_PERMISSIONS defines the feature vector. Training and
scanning both import this list, so they can never disagree. If you change it,
you must rebuild the dataset and retrain; the saved model stores the schema
it was trained with and the scanner refuses to run on a mismatch.
"""

