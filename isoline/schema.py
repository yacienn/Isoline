# Order-sensitive fingerprint stored with the model.
SCHEMA_VERSION = 1

# Rule-of-thumb labels shown in the web UI. These are NOT model output.
_P = "android.permission."
HIGH_RISK = {_P + n for n in [
    "SEND_SMS", "READ_SMS", "RECEIVE_SMS", "WRITE_SMS", "RECEIVE_MMS", "RECEIVE_WAP_PUSH",
    "BIND_ACCESSIBILITY_SERVICE", "BIND_DEVICE_ADMIN", "SYSTEM_ALERT_WINDOW",
    "REQUEST_INSTALL_PACKAGES", "INSTALL_PACKAGES", "DELETE_PACKAGES",
    "READ_CALL_LOG", "WRITE_CALL_LOG", "PROCESS_OUTGOING_CALLS",
    "MANAGE_EXTERNAL_STORAGE", "READ_LOGS", "MOUNT_UNMOUNT_FILESYSTEMS"]}
MEDIUM_RISK = {_P + n for n in [
    "READ_CONTACTS", "WRITE_CONTACTS", "RECORD_AUDIO", "CAMERA", "ACCESS_FINE_LOCATION",
    "ACCESS_COARSE_LOCATION", "ACCESS_BACKGROUND_LOCATION", "READ_PHONE_STATE", "CALL_PHONE",
    "GET_ACCOUNTS", "MANAGE_ACCOUNTS", "USE_CREDENTIALS", "READ_CALENDAR", "GET_TASKS",
    "KILL_BACKGROUND_PROCESSES", "WRITE_SETTINGS", "READ_PHONE_NUMBERS", "QUERY_ALL_PACKAGES",
    "READ_EXTERNAL_STORAGE", "WRITE_EXTERNAL_STORAGE", "DISABLE_KEYGUARD"]}


def risk_of(permission: str) -> str:
    if permission in HIGH_RISK:
        return "high"
    return "medium" if permission in MEDIUM_RISK else "low"
